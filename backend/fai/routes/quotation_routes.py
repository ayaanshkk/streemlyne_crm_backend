# Status change (shared by the status-only PUT and the full PUT)
# ═════════════════════════════════════════════════════════════════════════════
def _status_set_clauses(status_name, user_id):
    """SET clauses + params for a status change. Approved stamps the
    approver/date; moving to any other status clears them."""
    clauses = ['"Status_ID" = :status_id', '"Updated_At" = NOW()', '"Updated_By" = :uid']
    params = {"uid": user_id}
    if (status_name or "").lower() == "approved":
        clauses += ['"Approved_By_User_ID" = :uid', '"Approval_Date" = :today']
        params["today"] = _today_ist()
    else:
        clauses += ['"Approved_By_User_ID" = NULL', '"Approval_Date" = NULL']
    return clauses, params


def _notify_status_change(session, row, meta, status_name, user_id):
    if status_name not in ('Sent', 'Approved', 'Rejected'):
        return
    client_info = _get_client_info(session, row.client_id)
    qnum = row.quotation_number
    cust = meta.get("customer_name") or client_info.get("customer_name") or "Client"
    msg_map = {
        'Sent':     f"📤 Quotation {qnum} for {cust} has been marked as Sent",
        'Approved': f"✅ Quotation {qnum} for {cust} has been Approved",
        'Rejected': f"❌ Quotation {qnum} for {cust} has been Rejected",
    }
    create_notification(
        session,
        message=msg_map[status_name],
        notification_type="quotation",
        client_id=row.client_id,
        created_by_employee_id=_get_employee_id(session, user_id),
        priority="high" if status_name == 'Approved' else "medium",
    )


