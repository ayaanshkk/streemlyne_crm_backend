def _today_ist() -> date:
    return datetime.now(IST).date()


def _num(value, default=0.0) -> float:
    if value is None or value == "":
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _r2(value) -> float:
    return round(float(value or 0), 2)


def _clean_qty(value):
    """Quantity is a float column; show whole numbers without the .0."""
    q = float(value or 0)
    return int(q) if q.is_integer() else q


def _parse_date(value):
    if not value:
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).date()
    except ValueError:
        return None


def _split_terms(terms) -> list:
    return [t.strip() for t in (terms or "").splitlines() if t.strip()]


def _terms_from_payload(d: dict):
    """Returns the text for the `terms` column, or None if the payload
    carries no terms at all (so an update leaves the column alone)."""
    if "terms_conditions" in d:
        raw = d.get("terms_conditions")
    elif "terms" in d:
        raw = d.get("terms")
    else:
        return None
    if isinstance(raw, (list, tuple)):
        seen, out = set(), []
        for t in raw:
            clean = (t or "").strip()
            if clean and clean.lower() not in seen:
                seen.add(clean.lower())
                out.append(clean)
        return "\n".join(out)
    return (raw or "").strip()


