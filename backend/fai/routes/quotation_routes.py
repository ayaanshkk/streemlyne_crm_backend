@quotation_bp.route('/quotations/<int:quotation_id>', methods=['PUT', 'OPTIONS'])
@token_required
def update_quotation(quotation_id):
    if request.method == 'OPTIONS':
        return jsonify({}), 200
    session = SessionLocal()
    try:
        d = request.get_json() or {}
        user_id = request.current_user.id

        existing = _fetch_header(session, quotation_id)
        if not existing:
            return jsonify({"error": "Quotation not found"}), 404
        old_meta = _unpack_notes(existing.notes)

        # ── Status-only update (list-page dropdown) ──────────────────────────
        if list(d.keys()) in (['status'], ['status_id']):
            status_id, status_name = _resolve_status(session, d.get("status"), d.get("status_id"))
            clauses, params = _status_set_clauses(status_name, user_id)
            params.update({"status_id": status_id, "qid": quotation_id, "tid": TENANT_ID})
            session.execute(
                text(f"""
                    UPDATE {T_MASTER} SET {", ".join(clauses)}
                    WHERE "Quotation_ID" = :qid AND "Tenant_ID" = :tid
                """),
                params
            )
            session.commit()

            if status_id != existing.status_id:
                _notify_status_change(session, existing, old_meta, status_name, user_id)
                session.commit()
            return jsonify({"quotation_id": quotation_id, "status": status_name}), 200

        # ── Full update ─────────────────────────────────────────────────────
        # Quotation_Number is never changed by an edit.
        client_id = d.get("client_id") or d.get("customer_id") or existing.client_id

        gd = _num(d.get("discount_percentage", d.get("discount_percent")), float(existing.discount_percent or 0))
        tax_id = _resolve_tax_id(session, d.get("igst_percentage"), d.get("tax_id"))

        if "items" in d:
            lines, sub_total, tax_amount = _compute_lines(session, d.get("items", []), tax_id, gd)
        else:
            lines = None
            # Items untouched: keep stored lines, re-price them only if the
            # global discount changed (line tax depends on it).
            items_now = _get_quotation_items(session, quotation_id)
            if gd != float(existing.discount_percent or 0) and items_now:
                lines, sub_total, tax_amount = _compute_lines(
                    session,
                    [{**i, "service_rate": i["service_rate"], "discount_amount": i["discount_amount"]}
                     for i in items_now],
                    tax_id, gd
                )
            else:
                sub_total, tax_amount = float(existing.sub_total or 0), float(existing.tax_amount or 0)

        quotation_date = _parse_date(d.get("quotation_date") or d.get("date")) or existing.quotation_date
        if _parse_date(d.get("valid_until")):
            valid_until = _parse_date(d.get("valid_until"))
        elif d.get("valid_for_days"):
            valid_until = quotation_date + timedelta(days=int(d.get("valid_for_days")))
        else:
            valid_until = existing.valid_until

        merged = dict(old_meta)
        merged["notes"] = old_meta.get("user_notes", "")
        merged.update(d)
        terms = _terms_from_payload(d)

        set_clauses = [
            '"Client_ID" = :client_id', '"Lead_ID" = :lead_id', '"Project_ID" = :project_id',
            '"Contact_ID" = :contact_id', '"Currency_ID" = :currency_id',
            '"Quotation_Date" = :quotation_date', '"Valid_Until" = :valid_until',
            '"Sub_Total" = :sub_total', '"Tax_Amount" = :tax_amount',
            '"Discount_percent" = :discount_percent', 'notes = :notes', 'terms = :terms',
            '"Updated_At" = NOW()', '"Updated_By" = :uid',
        ]
        params = {
            "qid":              quotation_id,
            "tid":              TENANT_ID,
            "uid":              user_id,
            "client_id":        client_id,
            "lead_id":          d["lead_id"] if "lead_id" in d else existing.lead_id,
            "project_id":       d["project_id"] if "project_id" in d else existing.project_id,
            "contact_id":       d["contact_id"] if "contact_id" in d else existing.contact_id,
            "currency_id":      d["currency_id"] if "currency_id" in d else existing.currency_id,
            "quotation_date":   quotation_date,
            "valid_until":      valid_until,
            "sub_total":        sub_total,
            "tax_amount":       tax_amount,
            "discount_percent": gd,
            "notes":            _pack_notes(merged),
            "terms":            terms if terms is not None else (existing.terms or ""),
        }

        new_status_name = existing.status
        if d.get("status") or d.get("status_id"):
            status_id, new_status_name = _resolve_status(session, d.get("status"), d.get("status_id"))
            if status_id != existing.status_id:
                clauses, status_params = _status_set_clauses(new_status_name, user_id)
                # Updated_At/Updated_By are already in set_clauses above.
                set_clauses += [c for c in clauses if not c.startswith('"Updated_')]
                params.update({k: v for k, v in status_params.items() if k != "uid"})
                params["status_id"] = status_id

        session.execute(
            text(f"""
                UPDATE {T_MASTER} SET {", ".join(set_clauses)}
                WHERE "Quotation_ID" = :qid AND "Tenant_ID" = :tid
            """),
            params
        )
        if lines is not None:
            _insert_lines(session, quotation_id, lines)

        session.commit()

        if new_status_name != existing.status:
            _notify_status_change(session, existing, merged, new_status_name, user_id)
            session.commit()

        return jsonify({"quotation_id": quotation_id, "quotation_number": existing.quotation_number}), 200

    except QuotationValidationError as e:
        session.rollback()
        return jsonify({"error": str(e)}), 400
    except Exception as e:
        session.rollback()
        current_app.logger.error(f"Quotation update error: {e}")
        return jsonify({"error": str(e)}), 500
    finally:
        session.close()


