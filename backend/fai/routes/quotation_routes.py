def _unpack_notes(notes_str) -> dict:
    if not notes_str:
        return {}
    try:
        data = json.loads(notes_str)
        return data if isinstance(data, dict) else {"user_notes": notes_str}
    except Exception:
        return {"user_notes": notes_str}


