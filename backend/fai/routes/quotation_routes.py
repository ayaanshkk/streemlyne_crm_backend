def _load_quotation(session, quotation_id):
    """Returns (row, meta, items, quotation_dict) or None if not found."""
    row = _fetch_header(session, quotation_id)
    if not row:
        return None
    meta = _unpack_notes(row.notes)
    items = _get_quotation_items(session, quotation_id)
