# Line items
# ═════════════════════════════════════════════════════════════════════════════
def _compute_lines(session, items: list, default_tax_id, global_discount_percent: float):
    """Validate + price every item. Returns (lines, sub_total, tax_amount).
    Nothing is written here so the header can be inserted with real totals."""
    lines = []
    tax_rates = {}
    gd = global_discount_percent or 0

    def rate_for(tid):
        if tid not in tax_rates:
            tax_rates[tid] = _get_tax_rate(session, tid)
        return tax_rates[tid]

    for idx, item in enumerate(items or [], start=1):
        variant_id = item.get("variant_id") or item.get("product_variant_id")
        if not variant_id:
            raise QuotationValidationError(f"Item {idx}: variant_id (Product_Variant) is required")

        uom_id = item.get("uom_id")
        if not uom_id:
            raise QuotationValidationError(f"Item {idx}: uom_id is required")

        item_name = (item.get("service_title") or item.get("item_name")
                     or item.get("description") or "Item").strip() or "Item"

        quantity = _num(item.get("quantity"), 1.0)
        rate = _num(item.get("service_rate") if item.get("service_rate") not in (None, "")
                    else item.get("unit_rate"))
        # Same rule the frontend uses: quantity 0 means a flat rate.
        gross = rate if quantity == 0 else quantity * rate

        if item.get("discount_amount") not in (None, ""):
            discount = _num(item.get("discount_amount"))
        elif _num(item.get("discount_percent")) > 0:
            discount = gross * _num(item.get("discount_percent")) / 100
        else:
            discount = 0.0
        discount = min(max(discount, 0.0), gross)

        line_total = gross - discount
        tax_id = item.get("tax_id") or default_tax_id
        tax_rate = rate_for(tax_id) if tax_id else 0
        line_tax = line_total * (1 - gd / 100) * tax_rate / 100

        lines.append({
            "variant_id":      variant_id,
            "quantity":        quantity,
            "uom_id":          uom_id,
            "rate":            _r2(rate),
            "price_list_id":   item.get("pricelist_id") or item.get("price_list_id"),
            "discount_amount": _r2(discount),
            "tax_id":          tax_id,
            "tax_amount":      _r2(line_tax),
            "item_name":       item_name,
            "description":     item.get("description", "") or "",
            "total_amount":    _r2(line_total),
        })

    sub_total = _r2(sum(l["total_amount"] for l in lines))
    tax_amount = _r2(sum(l["tax_amount"] for l in lines))
    return lines, sub_total, tax_amount


def _insert_lines(session, quotation_id, lines: list):
    session.execute(
        text(f'DELETE FROM {T_DETAILS} WHERE "Quotation_ID" = :qid'),
        {"qid": quotation_id}
    )
    for l in lines:
        session.execute(
            text(f"""
                INSERT INTO {T_DETAILS} (
                    "Quotation_ID", "Product_Variant_ID", "Quantity", "UOM_ID", "Rate",
                    "Price_List_ID", "Discount_Amount", "Tax_ID", "Tax_Amount",
                    "Item_Name", "Description", "Total_Amount"
                ) VALUES (
                    :quotation_id, :variant_id, :quantity, :uom_id, :rate,
                    :price_list_id, :discount_amount, :tax_id, :tax_amount,
                    :item_name, :description, :total_amount
                )
            """),
            {"quotation_id": quotation_id, **l}
        )


def _get_quotation_items(session, quotation_id) -> list:
    rows = session.execute(
        text(f"""
            SELECT d."Quotation_Details_ID" AS item_id,
                   d."Product_Variant_ID"   AS variant_id,
                   d."Quantity"             AS quantity,
                   d."UOM_ID"               AS uom_id,
                   d."Rate"                 AS rate,
                   d."Price_List_ID"        AS pricelist_id,
                   d."Discount_Amount"      AS discount_amount,
                   d."Tax_ID"               AS tax_id,
                   d."Tax_Amount"           AS tax_amount,
                   d."Item_Name"            AS item_name,
                   d."Description"          AS description,
                   d."Total_Amount"         AS total_amount,
                   pm.item_code             AS item_code,
                   u.uom_code               AS uom_code
            FROM {T_DETAILS} d
            LEFT JOIN {T_VARIANT} pv ON pv.variant_id = d."Product_Variant_ID"
            LEFT JOIN {T_PRODUCT} pm ON pm.product_id = pv.product_id
            LEFT JOIN {T_UOM}     u  ON u.uom_id = d."UOM_ID"
            WHERE d."Quotation_ID" = :qid
            ORDER BY d."Quotation_Details_ID"
        """),
        {"qid": quotation_id}
    ).fetchall()

    items = []
    for r in rows:
        qty = float(r.quantity or 0)
        rate = float(r.rate or 0)
        gross = rate if qty == 0 else qty * rate
        disc = float(r.discount_amount or 0)
        items.append({
            "item_id":         r.item_id,
            "variant_id":      r.variant_id,
            "quantity":        _clean_qty(qty),
            "uom_id":          r.uom_id,
            "uom_code":        r.uom_code,
            "service_code":    r.item_code or "",
            "unit_rate":       rate,
            "service_rate":    rate,
            "service_title":   r.item_name or r.description or "-",
            "item_name":       r.item_name,
            "description":     r.description or "",
            "pricelist_id":    r.pricelist_id,
            "discount_amount": disc,
            "discount_percent": round(disc / gross * 100, 2) if gross else 0,
            "tax_id":          r.tax_id,
            "tax_amount":      float(r.tax_amount or 0),
            "amount":          float(r.total_amount or 0),
            "total_amount":    float(r.total_amount or 0),
        })
    return items


# ═════════════════════════════════════════════════════════════════════════════
# Totals + serialization — header Sub_Total / Tax_Amount are stored values
# ═════════════════════════════════════════════════════════════════════════════
def _compute_totals(sub_total: float, tax_amount: float, global_discount_percent: float) -> dict:
    discount_amount = sub_total * (global_discount_percent or 0) / 100
    total = sub_total - discount_amount + tax_amount
    return {
        "sub_total":       _r2(sub_total),
        "discount_amount": _r2(discount_amount),
        "tax_amount":      _r2(tax_amount),
        "total":           _r2(total),
    }


