def _resolve_status(session, name=None, status_id=None):
    """Returns (status_id, status_name) for a quotation status, or raises.
    Accepts either the name ('Draft') or the id; defaults to Draft."""
    statuses = _get_statuses(session)
    if status_id not in (None, ""):
        for s in statuses:
            if str(s["status_id"]) == str(status_id):
                return s["status_id"], s["status"]
    else:
        wanted = (name or "Draft").strip().lower()
        for s in statuses:
            if (s["status"] or "").strip().lower() == wanted:
                return s["status_id"], s["status"]
    valid = ", ".join(s["status"] for s in statuses)
    raise QuotationValidationError(
        f"Invalid status: {name if status_id in (None, '') else status_id}. Valid statuses: {valid}"
    )


def _resolve_tax_id(session, igst_percentage, existing_tax_id=None):
    """Prefer an explicit tax_id; otherwise look up the active Tax_Master
    row whose tax_rate matches the percentage the frontend sends (default
    18), falling back to the first active tax row."""
    if existing_tax_id:
        return existing_tax_id
    if igst_percentage is None:
        igst_percentage = 18
    row = session.execute(
        text(f"SELECT tax_id FROM {T_TAX} WHERE tax_rate = :rate AND is_active = true LIMIT 1"),
        {"rate": igst_percentage}
    ).fetchone()
    if row:
        return row.tax_id
    fallback = session.execute(
        text(f"SELECT tax_id FROM {T_TAX} WHERE is_active = true ORDER BY tax_id LIMIT 1")
    ).fetchone()
    return fallback.tax_id if fallback else None


def _get_tax_rate(session, tax_id):
    if not tax_id:
        return 0
    row = session.execute(
        text(f"SELECT tax_rate FROM {T_TAX} WHERE tax_id = :tid"),
        {"tid": tax_id}
    ).fetchone()
    return float(row.tax_rate) if row else 0


# ═════════════════════════════════════════════════════════════════════════════
# Quotation number — YYYYMM + monthly sequence, generated from the database
# ═════════════════════════════════════════════════════════════════════════════
def _generate_quotation_number(session, tenant_id, on_date: date) -> str:
    prefix = on_date.strftime("%Y%m")                       # e.g. "202610"
    pattern = "^" + prefix + "[0-9]{1,6}$"

    # Serialise creators for this tenant+month until the surrounding
    # transaction commits, so two users can never read the same "last" number.
    session.execute(
        text("SELECT pg_advisory_xact_lock(:k)"),
        {"k": int(prefix) * 1000 + int(tenant_id)}
    )

    last = session.execute(
        text(f"""
            SELECT COALESCE(MAX(CAST(SUBSTRING(quotation_number FROM 7) AS BIGINT)), 0)
            FROM {T_MASTER}
            WHERE tenant_id = :tid AND quotation_number ~ :pattern
        """),
        {"tid": tenant_id, "pattern": pattern}
    ).scalar() or 0

    legacy_last = 0
    if INCLUDE_LEGACY_NUMBERS:
        try:
            with session.begin_nested():
                legacy_last = session.execute(
                    text(f"""
                        SELECT COALESCE(MAX(CAST(SUBSTRING(reference_number FROM 7) AS BIGINT)), 0)
                        FROM {T_LEGACY_MASTER}
                        WHERE tenant_id = :tid AND reference_number ~ :pattern
                    """),
                    {"tid": tenant_id, "pattern": pattern}
                ).scalar() or 0
        except Exception as e:
            current_app.logger.warning(f"Legacy quotation number lookup skipped: {e}")

    seq = max(int(last), int(legacy_last)) + 1
    return f"{prefix}{seq:02d}"


