"""
Quotation Routes for FAI CRM — DEV VERSION (streemLyne_mt_dev2)
──────────────────────────────────────────────────────────────────────────
REWRITTEN (2026-10-14) to use the new tables:

    "Quotation_Master_new"   (header)
    "Quotation_Details_new"  (line items)

The old Quotation_Master / Quotation_Details pair (and its doc_type
discriminator) is no longer touched for reads or writes. The Proposal
module is being removed, so there is no doc_type any more.

How each thing is stored now
─────────────────────────────
  Quotation_Number    Generated by the DATABASE, never taken from the
                      frontend. Format: YYYYMM + running sequence for that
                      month (20261001, 20261002 ... 20261032; first one in
                      November is 20261101). Sequence = highest existing
                      number for that month + 1, per tenant, padded to at
                      least 2 digits. An advisory lock serialises concurrent
                      creates, and migration_quotation_number_unique.sql adds
                      a unique index as a safety net. The number is
                      immutable: edits never change it.
  Status              Status_ID -> Status_Master (status_type = 2). Nothing
                      is hardcoded; names are resolved from the table.
  Header columns      Client_ID, Contact_ID, Lead_ID, Project_ID, Currency_ID,
                      Quotation_Date, Valid_Until, Discount_percent,
                      Sub_Total, Tax_Amount, notes, terms, Created_by_user_ID,
                      Approved_By_User_ID, Approval_Date, Updated_At/By.
  Line columns        Product_Variant_ID, Quantity, UOM_ID, Rate,
                      Price_List_ID, Discount_Amount, Tax_ID, Tax_Amount,
                      Item_Name, Description, Total_Amount.

Money rules (all rounded to 2 decimals)
  gross            = Quantity * Rate            (Quantity 0 = flat Rate)
  Discount_Amount  = line discount in currency
  Total_Amount     = gross - Discount_Amount    (line total, EXCLUDING tax)
  Tax_Amount(line) = Total_Amount * (1 - Discount_percent/100) * tax rate
  Sub_Total(hdr)   = sum of line Total_Amount
  Tax_Amount(hdr)  = sum of line Tax_Amount
  Grand total      = Sub_Total - Sub_Total*Discount_percent/100 + Tax_Amount
  (Discount_percent is the global discount, applied before tax.)

⚠️ OPEN ASSUMPTIONS
  1. Product_Variant_ID and UOM_ID are NOT NULL on the line table, so every
     item MUST carry variant_id and uom_id (a missing one is a 400 error —
     there is deliberately no default, a guessed unit would be wrong data).
     The /pricelist endpoint needs to return a numeric uom_id per row.
  2. These fields still have NO column on Quotation_Master_new, so they
     keep riding in the notes column as JSON (same pattern as before, the
     typed note text lives under "user_notes"): customer_name/address/
     mobile/email/designation/company/gst, payment_terms, mode_of_enquiry
     and the bank/GST/PAN block. Adding real columns for payment_terms and
     mode_of_enquiry at least is recommended.
  3. There is no Quotation_Master_new.created_at; "date"/"created_at" in
     API responses are Quotation_Date.
  4. Created_by/Approved_By/Updated_By are User_Master ids, so the logged-in
     user's id is used directly. _get_employee_id() is kept only because the
     notification helper still takes an employee id.
"""

